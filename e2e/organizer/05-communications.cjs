// Communications: draft save -> edit -> delete; send to one event's registrants (in-app
// notification reaches the attendee; Sent history; audit); email template use; announcements
// post (pinned) -> unpin/pin -> draft + publish now -> delete.
const L = require('./lib.cjs')

L.run('05-communications', async (T, browser) => {
  const S = L.state()
  const A = S.eventA
  if (!A || !S.att1) throw new Error('Run 01-03 first')
  const db = L.db()
  const { orgId } = await L.orgIds()
  const evTitle = (await db.event.findUnique({ where: { id: A.id }, select: { title: true } })).title
  const org = await L.session(browser, 'alice')
  const drafts = async () => {
    const o = await db.organization.findUnique({ where: { id: orgId }, select: { settings: true } })
    return (o.settings && o.settings.communicationDrafts) || []
  }
  const subj = `${L.TITLE_PREFIX} Draft ${S.runId}`

  await T.step('save a draft', async () => {
    await L.goto(org, '/admin/org/communications')
    await org.waitForSelector('#comm-subject', { timeout: 20000 })
    await L.selectOption(org, '#comm-recipients', 'Participants of one event')
    await L.selectOption(org, '#comm-event', evTitle)
    await L.typeInto(org, '#comm-subject', subj)
    await L.typeInto(org, '#comm-body', 'Hello ')
    await L.clickText(org, /^Name$/, 'button')
    const body = await org.$eval('#comm-body', (e) => e.value)
    T.ok('merge tag button inserts {{participant_name}}', body.includes('{{participant_name}}'), body)
    await L.clearToasts(org)
    await L.clickText(org, 'Save as draft')
    const toast = await L.waitToast(org)
    T.ok('"Draft saved" toast', toast && /draft saved/i.test(toast.text), toast)
    const d = (await drafts()).find((x) => x.subject === subj)
    T.ok('draft stored with the event as recipients', d && d.recipientFilter.type === 'by_event' && d.recipientFilter.eventId === A.id, d)
    if (d) L.setState('draftId', d.id)
    await L.clickText(org, /^Drafts/, '[role="tab"]')
    T.ok('Drafts tab lists it', await L.waitText(org, subj, 8000))
  })

  await T.step('edit the draft', async () => {
    const row = await L.findByText(org, 'li', subj)
    await (await row.$('button')).click() // Edit
    await org.waitForSelector('#comm-subject')
    T.ok('composer says it is editing a draft', await L.waitText(org, 'Editing a draft', 8000))
    T.ok('composer restored the event recipients', (await L.bodyText(org)).includes(evTitle))
    await L.typeInto(org, '#comm-subject', `${subj} v2`)
    await L.clearToasts(org)
    await L.clickText(org, 'Update draft')
    const toast = await L.waitToast(org)
    T.ok('"Draft updated" toast', toast && /updated/i.test(toast.text), toast)
    const all = await drafts()
    T.ok('same draft updated (no duplicate)', all.filter((x) => x.subject.startsWith(subj)).length === 1 && all.some((x) => x.id === L.state().draftId && x.subject === `${subj} v2`), all.map((x) => x.subject))
  })

  await T.step('delete the draft', async () => {
    await L.clickText(org, /^Drafts/, '[role="tab"]')
    await L.waitText(org, `${subj} v2`, 8000)
    const row = await L.findByText(org, 'li', `${subj} v2`)
    const btns = await row.$$('button')
    await btns[1].click() // Delete
    T.ok('delete asks for confirmation', await L.waitText(org, 'Delete this draft?', 8000))
    await L.clearToasts(org)
    await L.clickText(org, /^Delete$/, '[role="dialog"] button')
    const toast = await L.waitToast(org)
    T.ok('"Draft deleted" toast', toast && /deleted/i.test(toast.text), toast)
    T.ok('draft gone from storage', !(await drafts()).some((x) => x.subject.startsWith(subj)))
  })

  await T.step('send to one event\'s registrants', async () => {
    const sendSubj = `${L.TITLE_PREFIX} Venue update ${S.runId}`
    L.setState('sentSubject', sendSubj)
    await L.goto(org, '/admin/org/communications')
    await org.waitForSelector('#comm-subject', { timeout: 20000 })
    const defaultRecipients = await org.$eval('#comm-recipients', (e) => e.innerText.trim())
    T.info(`default recipients: "${defaultRecipients}"`)
    await L.selectOption(org, '#comm-recipients', 'Participants of one event')
    await L.selectOption(org, '#comm-event', evTitle)
    await L.typeInto(org, '#comm-subject', sendSubj)
    await L.typeInto(org, '#comm-body', 'Hi {{participant_name}}, the venue moved to Hall B.')
    const expected = await db.registration.findMany({ where: { eventId: A.id, status: { in: ['PENDING', 'CONFIRMED', 'WAITLISTED', 'CHECKED_IN', 'NO_SHOW'] } }, select: { userId: true } })
    await L.clearToasts(org)
    await L.clickText(org, 'Send now')
    await L.sleep(700)
    const confirmDialog = await org.$('[role="dialog"]')
    if (confirmDialog) { T.info('send asked for confirmation'); await L.clickText(org, /send/i, '[role="dialog"] button') }
    else T.uxIssue('major', '/admin/org/communications (Compose -> Send now)', `"Send now" emails immediately with no confirmation and no recipient count; the Recipients default is "${defaultRecipients}" (everyone registered for any of the club's events, all statuses but cancelled/rejected). One click on a half-written message reaches every past participant.`, 'Show a confirm step "Send to N people (event / statuses)?" with a test-send-to-me option; default Recipients to "Participants of one event".')
    const toast = await L.waitToast(org)
    T.ok(`"Email queued for ${expected.length} recipients" toast`, toast && toast.text.includes(`${expected.length} recipient`), toast)
    await L.sleep(800)
    const n1 = await db.notification.findFirst({ where: { userId: S.att1.id, title: sendSubj, eventId: A.id } })
    T.ok('attendee (att1) gets an in-app notification for the message', !!n1)
    const n3 = await db.notification.findFirst({ where: { userId: S.att3.id, title: sendSubj } })
    T.ok('rejected attendee (att3) is not messaged', !n3)
    const nOther = await db.notification.count({ where: { title: sendSubj, userId: { notIn: expected.map((e) => e.userId) } } })
    T.ok('nobody outside the event is messaged', nOther === 0, nOther)
    const audit = await db.auditLog.findFirst({ where: { organizationId: orgId, entityType: 'COMMUNICATION', description: { contains: sendSubj } } })
    T.ok('send is in the audit log (COMMUNICATION)', !!audit)
    await L.clickText(org, 'Sent', '[role="tab"]')
    T.ok('Sent tab lists the message with "One event"', await L.waitText(org, sendSubj, 10000) && (await L.bodyText(org)).includes('One event'))
    const p = await L.session(browser, S.att1)
    await L.goto(p, '/dashboard/notifications')
    T.ok('attendee sees the message in Notifications', await L.waitText(p, sendSubj, 15000))
    await L.shot(p, '05-attendee-notifications')
    await L.closeSession(p)
  })

  await T.step('email template use', async () => {
    await L.clickText(org, 'Templates', '[role="tab"]')
    const use = await org.$('button[aria-label^="Use the "]')
    T.ok('templates are listed with a Use button', !!use)
    if (use) {
      await use.click()
      await org.waitForSelector('#comm-subject')
      const s = await org.$eval('#comm-subject', (e) => e.value)
      const b = await org.$eval('#comm-body', (e) => e.value)
      T.ok('Use fills subject and message in Compose', s.length > 3 && b.length > 10, { s, b: b.slice(0, 80) })
      const nl = await L.findByText(org, 'button', 'New message', { timeout: 1000 })
      if (nl) await nl.click()
      await L.setValue(org, '#comm-subject', '')
      await L.setValue(org, '#comm-body', '')
    }
  })

  const annTitle = `${L.TITLE_PREFIX} Doors open ${S.runId}`
  await T.step('post a pinned announcement', async () => {
    await L.clickText(org, 'Announcements', '[role="tab"]')
    await L.clickText(org, 'New announcement')
    await org.waitForSelector('#ann-title')
    await L.selectOption(org, '#ann-event', evTitle)
    await L.typeInto(org, '#ann-title', annTitle)
    await L.typeInto(org, '#ann-content', 'Doors open at 9:30, bring your ticket QR.')
    await L.setSwitch(org, '[role="switch"]#ann-pin', true).catch(async () => { await org.click('label[for="ann-pin"]') })
    const reach = await db.registration.count({ where: { eventId: A.id, status: { in: ['CONFIRMED', 'CHECKED_IN'] } } })
    await L.clearToasts(org)
    await L.clickText(org, /^Post$/, '[role="dialog"] button')
    const toast = await L.waitToast(org)
    T.ok(`"Announcement posted to ${reach} participants" toast`, toast && toast.text.includes(`${reach} participant`), toast)
    const a = await db.announcement.findFirst({ where: { eventId: A.id, title: annTitle } })
    T.ok('announcement stored, published and pinned', a && !!a.publishedAt && a.isPinned, a && { pinned: a.isPinned, published: !!a.publishedAt })
    if (a) L.setState('announcementId', a.id)
    T.ok('confirmed attendee notified', !!(await db.notification.findFirst({ where: { userId: S.att1.id, title: { contains: annTitle } } })))
    T.ok('pending (unpaid) attendee not notified', !(await db.notification.findFirst({ where: { userId: S.att4.id, title: { contains: annTitle } } })))
    T.ok('list shows it with the pin marker', await L.waitText(org, annTitle, 8000) && !!(await org.$('[aria-label="Pinned"]')))
    const anon = await L.session(browser, null)
    await L.goto(anon, `/events/${A.slug}`)
    const pub = (await L.bodyText(anon)).includes(annTitle)
    T.info(`announcement visible on the public event page: ${pub}`)
    if (!pub) T.uxIssue('minor', '/admin/org/communications (Announcements: Pin to top)', 'Announcements reach attendees only as notifications; they are not shown on the event page, so "Pin to top" has no effect anyone outside the admin list can see.', 'Show published announcements (pinned first) on the public event page and the attendee ticket view, or drop the pin option.')
    await L.closeSession(anon)
  })

  await T.step('unpin, pin again, delete', async () => {
    const id = L.state().announcementId
    const menu = async (item) => {
      await org.click(`button[aria-label="Actions for ${annTitle}"]`)
      await L.clearToasts(org)
      await L.clickText(org, item, '[role="menuitem"]')
    }
    await menu('Unpin')
    await L.waitToast(org)
    await L.sleep(500)
    T.ok('unpinned', (await db.announcement.findUnique({ where: { id } })).isPinned === false)
    await menu('Pin to top')
    await L.waitToast(org)
    await L.sleep(500)
    T.ok('pinned again', (await db.announcement.findUnique({ where: { id } })).isPinned === true)
    await menu('Delete')
    await L.waitText(org, 'Delete', 5000)
    await L.clickText(org, /^Delete$/, '[role="dialog"] button')
    const toast = await L.waitToast(org)
    T.ok('delete toast', toast && /delet/i.test(toast.text), toast)
    await L.sleep(500)
    T.ok('announcement deleted', !(await db.announcement.findUnique({ where: { id } })))
  })

  await T.step('announcement draft, then Publish now', async () => {
    const t2 = `${annTitle} (draft)`
    await L.clickText(org, 'New announcement')
    await org.waitForSelector('#ann-title')
    await L.selectOption(org, '#ann-event', evTitle)
    await L.typeInto(org, '#ann-title', t2)
    await L.typeInto(org, '#ann-content', 'Draft first.')
    await L.clearToasts(org)
    await L.clickText(org, /save as draft/i, '[role="dialog"] button')
    await L.waitToast(org)
    const a = await db.announcement.findFirst({ where: { title: t2 } })
    T.ok('draft announcement saved unpublished, nobody notified', a && !a.publishedAt && !(await db.notification.findFirst({ where: { title: { contains: t2 } } })))
    await L.waitText(org, t2, 8000)
    await org.click(`button[aria-label="Actions for ${t2}"]`)
    await L.clickText(org, 'Publish now', '[role="menuitem"]')
    await L.waitText(org, 'Also send by email', 5000)
    await L.clearToasts(org)
    const btn = await L.findByText(org, '[role="dialog"] button', /publish/i)
    await btn.click()
    const toast = await L.waitToast(org)
    T.ok('Publish now toast', toast && toast.type !== 'error', toast)
    const a2 = await db.announcement.findFirst({ where: { title: t2 } })
    T.ok('published and attendees notified', a2 && !!a2.publishedAt && !!(await db.notification.findFirst({ where: { userId: S.att1.id, title: { contains: t2 } } })))
  })
  await L.closeSession(org)
})
