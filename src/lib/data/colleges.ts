/** Search colleges with fuzzy matching */
export function searchColleges(query: string, limit = 8): string[] {
  if (!query || query.length < 2) return []
  const q = query.toLowerCase()
  return COLLEGES.filter(c => c.toLowerCase().includes(q)).slice(0, limit)
}

/** Search companies with fuzzy matching */
export function searchCompanies(query: string, limit = 8): string[] {
  if (!query || query.length < 2) return []
  const q = query.toLowerCase()
  return COMPANIES.filter(c => c.toLowerCase().includes(q)).slice(0, limit)
}
